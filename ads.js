// AdSense placement manager.
//
// Pages declare where an ad may go:   <div class="ad-slot ad-slot--display" data-ad="HOME_AFTER_COUNTDOWN"></div>
// This file decides what (if anything) is rendered there. To turn a placement off everywhere,
// set `enabled: false` below. The AdSense library itself is loaded once per page in <head>.
(function () {
    'use strict';

    var CLIENT = 'ca-pub-7982216026691433';

    // format: 'display' (responsive), 'in-article', 'multiplex', 'fixed' (width/height)
    // minViewport: only render when the viewport is at least this wide (px)
    var PLACEMENTS = {
        // Home
        HOME_SIDE_LEFT: { slot: '1486507879', format: 'fixed', width: 300, height: 600, minViewport: 1840, enabled: true },
        HOME_SIDE_RIGHT: { slot: '1451380053', format: 'fixed', width: 300, height: 600, minViewport: 1840, enabled: true },
        HOME_AFTER_COUNTDOWN: { slot: '6547262869', format: 'display', enabled: true },
        HOME_AFTER_WISHES: { slot: '4120410073', format: 'display', enabled: true },
        HOME_CONTENT_1: { slot: '2663060381', format: 'in-article', enabled: true },
        HOME_CONTENT_2: { slot: '7408810597', format: 'in-article', enabled: true },
        HOME_MULTIPLEX: { slot: '7172814982', format: 'multiplex', enabled: true },

        // Blog articles
        ARTICLE_INTRO: { slot: '2968493398', format: 'display', enabled: true },
        ARTICLE_MIDDLE: { slot: '2575094426', format: 'in-article', enabled: true },
        ARTICLE_END: { slot: '4028430170', format: 'display', enabled: true },
        ARTICLE_MULTIPLEX: { slot: '7172814982', format: 'multiplex', enabled: true },

        // Blog index
        BLOG_INDEX_END: { slot: '6885376420', format: 'display', enabled: true },

        // Countdown-by-country hub and country pages (generated by seo/build.js)
        COUNTRY_AFTER_COUNTDOWN: { slot: '7090526020', format: 'display', enabled: true },
        COUNTRY_MIDDLE: { slot: '2575094426', format: 'in-article', enabled: true },
        COUNTRY_MULTIPLEX: { slot: '7172814982', format: 'multiplex', enabled: true }
    };

    // Rewarded ad (Google Ad Manager) for the free wish. Paste the ad unit path from Ad Manager,
    // e.g. '/1234567/newyeartimers_rewarded'. Empty = no rewarded ad (the free wish falls back to
    // one per visitor per day, see script.js).
    var REWARDED = { adUnitPath: '', timeoutMs: 8000 };

    var LABELS = { es: 'Publicidad', en: 'Advertisement' };
    var label = LABELS[(document.documentElement.lang || 'en').slice(0, 2)] || LABELS.en;

    function buildIns(p) {
        var ins = document.createElement('ins');
        ins.className = 'adsbygoogle';
        ins.setAttribute('data-ad-client', CLIENT);
        ins.setAttribute('data-ad-slot', p.slot);
        if (p.format === 'fixed') {
            ins.style.cssText = 'display:inline-block;width:' + p.width + 'px;height:' + p.height + 'px';
        } else if (p.format === 'in-article') {
            ins.style.cssText = 'display:block;text-align:center';
            ins.setAttribute('data-ad-layout', 'in-article');
            ins.setAttribute('data-ad-format', 'fluid');
        } else if (p.format === 'multiplex') {
            ins.style.display = 'block';
            ins.setAttribute('data-ad-format', 'autorelaxed');
        } else {
            ins.style.display = 'block';
            ins.setAttribute('data-ad-format', 'auto');
            ins.setAttribute('data-full-width-responsive', 'true');
        }
        return ins;
    }

    function render(el) {
        if (el.getAttribute('data-ad-state')) return;
        var p = PLACEMENTS[el.getAttribute('data-ad')];
        if (!p || !p.enabled) {
            el.setAttribute('data-ad-state', 'disabled');
            return;
        }
        // Hidden containers (e.g. side rails on small screens) never request an ad.
        if ((p.minViewport && window.innerWidth < p.minViewport) || el.offsetWidth === 0) return;
        el.setAttribute('data-ad-state', 'requested');
        el.appendChild(buildIns(p));
        try {
            (window.adsbygoogle = window.adsbygoogle || []).push({});
        } catch (e) {
            el.setAttribute('data-ad-state', 'error');
        }
    }

    var slots = [];
    var seen = {};
    document.querySelectorAll('.ad-slot[data-ad]').forEach(function (el) {
        var id = el.getAttribute('data-ad');
        // Each placement may appear once per page.
        if (seen[id]) {
            el.setAttribute('data-ad-state', 'disabled');
            return;
        }
        seen[id] = true;
        el.setAttribute('data-ad-label', label);
        var p = PLACEMENTS[id];
        if (!p || !p.enabled) el.setAttribute('data-ad-state', 'disabled');
        else slots.push(el);
    });

    function pending() {
        return slots.filter(function (el) { return !el.getAttribute('data-ad-state'); });
    }

    // Lazy-load: request each ad shortly before it scrolls into view.
    if ('IntersectionObserver' in window) {
        var io = new IntersectionObserver(function (entries) {
            entries.forEach(function (entry) {
                if (entry.isIntersecting) {
                    render(entry.target);
                    if (entry.target.getAttribute('data-ad-state')) io.unobserve(entry.target);
                }
            });
        }, { rootMargin: '600px 0px' });
        slots.forEach(function (el) { io.observe(el); });
        // Fixed side rails are always "in view"; re-check them when the window grows.
        window.addEventListener('resize', function () {
            pending().forEach(function (el) {
                var r = el.getBoundingClientRect();
                if (r.top < window.innerHeight + 600 && r.bottom > -600) render(el);
            });
        });
    } else {
        slots.forEach(render);
    }

    // --- Rewarded ad ---------------------------------------------------------------------------
    // The user explicitly asks to watch an ad (button click); the reward is granted only when
    // Google fires rewardedSlotGranted. Never ask for or reward clicks on ads.
    var gptLoading = null;

    function loadGpt() {
        if (!gptLoading) {
            gptLoading = new Promise(function (resolve, reject) {
                var s = document.createElement('script');
                s.src = 'https://securepubads.g.doubleclick.net/tag/js/gpt.js';
                s.async = true;
                s.onload = resolve;
                s.onerror = function () { gptLoading = null; reject(new Error('gpt.js failed to load')); };
                document.head.appendChild(s);
            });
        }
        return gptLoading;
    }

    // Resolves to 'granted' (ad watched), 'closed' (closed before the reward) or
    // 'unavailable' (not configured, blocked, unsupported page or no ad to show).
    function showRewarded() {
        if (!REWARDED.adUnitPath) return Promise.resolve('unavailable');
        window.googletag = window.googletag || { cmd: [] };
        return loadGpt().then(function () {
            return new Promise(function (resolve) {
                googletag.cmd.push(function () {
                    var slot = googletag.defineOutOfPageSlot(REWARDED.adUnitPath, googletag.enums.OutOfPageFormat.REWARDED);
                    if (!slot) return resolve('unavailable');
                    slot.addService(googletag.pubads());

                    var pubads = googletag.pubads();
                    var granted = false;
                    var done = false;
                    var timer = setTimeout(function () { finish('unavailable'); }, REWARDED.timeoutMs);
                    var handlers = {
                        rewardedSlotReady: function (e) {
                            if (e.slot !== slot) return;
                            clearTimeout(timer);
                            e.makeRewardedVisible();
                        },
                        rewardedSlotGranted: function (e) {
                            if (e.slot === slot) granted = true;
                        },
                        rewardedSlotClosed: function (e) {
                            if (e.slot === slot) finish(granted ? 'granted' : 'closed');
                        },
                        slotRenderEnded: function (e) {
                            if (e.slot === slot && e.isEmpty) finish('unavailable');
                        }
                    };

                    function finish(result) {
                        if (done) return;
                        done = true;
                        clearTimeout(timer);
                        Object.keys(handlers).forEach(function (name) {
                            if (pubads.removeEventListener) pubads.removeEventListener(name, handlers[name]);
                        });
                        googletag.destroySlots([slot]);
                        resolve(result);
                    }

                    Object.keys(handlers).forEach(function (name) { pubads.addEventListener(name, handlers[name]); });
                    googletag.enableServices();
                    googletag.display(slot);
                });
            });
        }).catch(function () { return 'unavailable'; });
    }

    window.NYTAds = {
        rewardedEnabled: !!REWARDED.adUnitPath,
        showRewarded: showRewarded
    };
})();
